from re import Pattern, compile

# ==================================================================================================
ANSI_RE = compile(r"\x1B(?:[@-Z\\-_]|\[[0-?]*[ -/]*[@-~])")
# ==================================================================================================

# ==================================================================================================
def StripAnsi(text):   
    return ANSI_RE.sub("", text) if isinstance(text, str) else text
