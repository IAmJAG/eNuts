# ==================================================================================
from __future__ import annotations

# ==================================================================================
from enum import IntFlag, auto


# ==================================================================================
class eSlotFlag(IntFlag):
    FREE = auto()
    FILLED = auto() # READY FOR DISPLAY    
    INUSE = auto()
    INVALIDATED = auto() # READY FOR OVERWRITE
    WRITING = auto() # CURRENTLY WRITING

# ==================================================================================
__all__ = ["eSlotFlag"]
