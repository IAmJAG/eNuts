# ==================================================================================
from __future__ import annotations

# ==================================================================================
import collections.abc

# ==================================================================================
from typing import Any, List, Protocol, overload, runtime_checkable

# ==================================================================================
from PySide6.QtCore import QByteArray, QEvent, QPoint, QSize, Qt
from PySide6.QtGui import QContextMenuEvent
from PySide6.QtWidgets import (
    QDockWidget,
    QMainWindow,
    QMenu,
    QMenuBar,
    QStatusBar,
    QTabWidget,
    QToolBar,
    QWidget,
)


# ==================================================================================
# Protocol-only: must NOT be a regular base class in the runtime MRO of any
# QMainWindow subclass. A normal class with "def event(...) -> bool: ..." would
# sit before QMainWindow in the MRO and return None, breaking Qt event delivery
# and often stopping the qasync loop immediately after show().
# ==================================================================================
@runtime_checkable
class iQMainWindow(Protocol):
    @overload
    def addDockWidget(self, area: Qt.DockWidgetArea, dockwidget: QDockWidget) -> None: ...
    @overload
    def addDockWidget(
        self, area: Qt.DockWidgetArea, dockwidget: QDockWidget, orientation: Qt.Orientation
    ) -> None: ...
    @overload
    def addToolBar(self, toolbar: QToolBar) -> None: ...
    @overload
    def addToolBar(self, area: Qt.ToolBarArea, toolbar: QToolBar) -> None: ...
    @overload
    def addToolBar(self, title: str) -> QToolBar: ...
    def addToolBarBreak(self, area: Qt.ToolBarArea) -> None: ...
    def centralWidget(self) -> QWidget: ...
    def contextMenuEvent(self, event: QContextMenuEvent) -> None: ...
    def corner(self, corner: Qt.Corner) -> Qt.DockWidgetArea: ...
    def createPopupMenu(self) -> QMenu: ...
    def dockOptions(self) -> QMainWindow.DockOption: ...
    def dockWidgetArea(self, dockwidget: QDockWidget) -> Qt.DockWidgetArea: ...
    def documentMode(self) -> bool: ...
    def event(self, event: QEvent) -> bool: ...
    def iconSize(self) -> QSize: ...
    def insertToolBar(self, before: QToolBar, toolbar: QToolBar) -> None: ...
    def insertToolBarBreak(self, before: QToolBar) -> None: ...
    def isAnimated(self) -> bool: ...
    def isDockNestingEnabled(self) -> bool: ...
    def isSeparator(self, pos: QPoint) -> bool: ...
    def menuBar(self) -> QMenuBar: ...
    def menuWidget(self) -> QWidget: ...
    def removeDockWidget(self, dockwidget: QDockWidget) -> None: ...
    def removeToolBar(self, toolbar: QToolBar) -> None: ...
    def removeToolBarBreak(self, before: QToolBar) -> None: ...
    def resizeDocks(
        self, docks: collections.abc.Sequence[QDockWidget],
        sizes: collections.abc.Sequence[int], orientation: Qt.Orientation) -> None: ...
    def restoreDockWidget(self, dockwidget: QDockWidget) -> bool: ...
    def restoreState(
        self, state: QByteArray | bytes | bytearray | memoryview, version: int | None = ...
    ) -> bool: ...
    def saveState(self, /, version: int | None = ...) -> QByteArray: ...
    def setAnimated(self, enabled: bool) -> None: ...
    def setCentralWidget(self, widget: QWidget) -> None: ...
    def setCorner(self, corner: Qt.Corner, area: Qt.DockWidgetArea) -> None: ...
    def setDockNestingEnabled(self, enabled: bool) -> None: ...
    def setDockOptions(self, options: QMainWindow.DockOption) -> None: ...
    def setDocumentMode(self, enabled: bool) -> None: ...
    def setIconSize(self, iconSize: QSize) -> None: ...
    def setMenuBar(self, menubar: QMenuBar) -> None: ...
    def setMenuWidget(self, menubar: QWidget) -> None: ...
    def setStatusBar(self, statusbar: QStatusBar) -> None: ...
    def setTabPosition(self, areas: Qt.DockWidgetArea, tabPosition: QTabWidget.TabPosition) -> None: ...
    def setTabShape(self, tabShape: QTabWidget.TabShape) -> None: ...
    def setToolButtonStyle(self, toolButtonStyle: Qt.ToolButtonStyle) -> None: ...
    def setUnifiedTitleAndToolBarOnMac(self, set: bool) -> None: ...
    def splitDockWidget(
        self, after: QDockWidget, dockwidget: QDockWidget, orientation: Qt.Orientation
    ) -> None: ...
    def statusBar(self) -> QStatusBar: ...
    def tabPosition(self, area: Qt.DockWidgetArea) -> QTabWidget.TabPosition: ...
    def tabShape(self) -> QTabWidget.TabShape: ...
    def tabifiedDockWidgets(self, dockwidget: QDockWidget) -> List[QDockWidget]: ...
    def tabifyDockWidget(self, first: QDockWidget, second: QDockWidget) -> None: ...
    def takeCentralWidget(self) -> QWidget: ...
    def toolBarArea(self, toolbar: QToolBar) -> Qt.ToolBarArea: ...
    def toolBarBreak(self, toolbar: QToolBar) -> bool: ...
    def toolButtonStyle(self) -> Qt.ToolButtonStyle: ...
    def unifiedTitleAndToolBarOnMac(self) -> bool: ...
